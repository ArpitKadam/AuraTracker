// Run: node scripts/gen-ingredient-icons.mjs
// Copies the extracted icon PNGs (personal use only, gitignored) and writes the static require() map React Native needs.
import { copyFileSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = 'C:/Projects/ReciBites/apk-extract/ingredients-raw/res/drawable-mdpi-v4';
const DST = 'src/recipe-module/assets/ingredients';
mkdirSync(DST, { recursive: true });

const keys = readdirSync(SRC)
  .filter((f) => /^assets_ingredients_.+\.png$/.test(f))
  .map((f) => f.replace(/^assets_ingredients_/, '').replace(/\.png$/, ''))
  .sort();
for (const k of keys) copyFileSync(join(SRC, `assets_ingredients_${k}.png`), join(DST, `${k}.png`));

const body = keys.map((k) => `  ${JSON.stringify(k)}: require('../assets/ingredients/${k}.png'),`).join('\n');
writeFileSync(
  'src/recipe-module/lib/ingredientIcons.generated.ts',
  `// Generated by scripts/gen-ingredient-icons.mjs. Do not edit.\nexport const INGREDIENT_ICONS: Record<string, number> = {\n${body}\n};\n`,
);
console.log(`${keys.length} icons`);
